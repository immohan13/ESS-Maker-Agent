"""SharePoint knowledge-source scaffolder.

Mirror of ess_maker.topics: a maker supplies a SharePoint URL + name and we
write a Copilot Studio knowledge-source YAML to a staging dir. Apply copies
into the HR solution under BotComponent_*/KnowledgeStaged/, then the publish
flow (`pac` CLI) packs + imports the solution.

The YAML shape is the documented Copilot Studio KnowledgeSource component
shape (kind: SearchAndSummarizeContent / DataSource: SharePoint). The maker
will need to bind a SharePoint connection reference in the Copilot Studio web
canvas before the source goes live — we mark that with a TODO.
"""
from __future__ import annotations

import json
import re
import time
import uuid
from dataclasses import dataclass, asdict
from pathlib import Path

from ess_maker.settings import settings


_SLUG_RE = re.compile(r"[^a-z0-9]+")


def _slug(s: str) -> str:
    s = _SLUG_RE.sub("-", (s or "").lower()).strip("-")
    return s[:48] or uuid.uuid4().hex[:8]


def staging_dir() -> Path:
    p = settings.ess_maker_workdir / "proposed-knowledge"
    p.mkdir(parents=True, exist_ok=True)
    return p


@dataclass
class KbScaffoldResult:
    ok: bool
    kb_id: str | None
    name: str | None
    url: str | None
    proposed_dir: str | None
    files: list[dict]
    notes: list[str]
    error: str | None = None


def render_kb_yaml(name: str, description: str, url: str, priority: int) -> str:
    """Produce a Copilot Studio knowledge-source YAML for a SharePoint site."""
    safe_name = name.replace('"', "'")
    safe_desc = (description or "").replace('"', "'").strip() or safe_name
    return f"""kind: SearchAndSummarizeContent
# Generated by ESS Maker.
# Display name: {safe_name}
# SharePoint URL: {url}
# Priority: {priority}

displayName: "{safe_name}"
description: |-
  {safe_desc}

dataSources:
  - kind: SharePoint
    # TODO(maker): bind a SharePoint connection reference in Copilot Studio
    # web canvas (Settings > Connections). Leave this blank to be prompted.
    connectionReference: ""
    sites:
      - url: "{url}"

# Search behaviour
searchOptions:
  maxResults: 5
  semanticRanker: true

# Higher priority sources are consulted first when answering.
priority: {priority}
"""


def scaffold_kb_source(name: str, description: str, url: str,
                       priority: int = 1) -> KbScaffoldResult:
    if not name.strip():
        return KbScaffoldResult(False, None, None, None, None, [], [], "name is required")
    if not url.strip():
        return KbScaffoldResult(False, None, None, None, None, [], [], "url is required")
    if not (url.startswith("http://") or url.startswith("https://")):
        return KbScaffoldResult(False, None, None, None, None, [], [],
                                "url must start with https://")

    kb_id = f"kb-{_slug(name)}-{uuid.uuid4().hex[:6]}"
    out_dir = staging_dir() / kb_id
    out_dir.mkdir(parents=True, exist_ok=True)

    yaml_text = render_kb_yaml(name, description, url, priority)
    yaml_path = out_dir / "knowledge.yaml"
    yaml_path.write_text(yaml_text, encoding="utf-8")

    meta = {
        "kb_id": kb_id,
        "name": name,
        "description": description,
        "url": url,
        "priority": priority,
        "created_at": time.time(),
        "applied": False,
    }
    (out_dir / "meta.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")

    return KbScaffoldResult(
        ok=True,
        kb_id=kb_id,
        name=name,
        url=url,
        proposed_dir=str(out_dir),
        files=[{
            "name": yaml_path.name,
            "path": str(yaml_path),
            "language": "yaml",
            "contents": yaml_text,
        }],
        notes=[
            f"Staged knowledge source at {out_dir}.",
            "Next: click **Apply** to copy into the HR solution, then **Publish** to import via pac CLI.",
            "After import, open Copilot Studio and bind a SharePoint connection reference if not already set.",
        ],
    )


def list_proposed() -> list[dict]:
    out = []
    base = staging_dir()
    for d in sorted(base.iterdir(), reverse=True) if base.exists() else []:
        meta_p = d / "meta.json"
        if not meta_p.exists():
            continue
        try:
            out.append(json.loads(meta_p.read_text(encoding="utf-8")) | {"path": str(d)})
        except Exception:
            pass
    return out


def apply_kb_to_solution(kb_id: str, target_solution_subdir: str | None = None) -> dict:
    src = staging_dir() / kb_id
    if not src.exists():
        return {"ok": False, "error": f"no such proposed kb: {kb_id}"}
    meta_p = src / "meta.json"
    meta = json.loads(meta_p.read_text(encoding="utf-8")) if meta_p.exists() else {}

    repo_root = Path(__file__).resolve().parents[4]
    if target_solution_subdir:
        dst_root = repo_root / target_solution_subdir
    else:
        dst_root = (
            repo_root
            / "sources" / "dev" / "solutions" / "CopilotForEmployeeSelfServiceHR"
            / "Solution" / "BotComponent_msdyn_copilotforemployeeselfservicehr"
            / "KnowledgeStaged"
        )
    dst_root.mkdir(parents=True, exist_ok=True)
    copied = []
    for f in src.iterdir():
        if f.name == "meta.json":
            continue
        target = dst_root / f"{kb_id}__{f.name}"
        target.write_text(f.read_text(encoding="utf-8"), encoding="utf-8")
        copied.append(str(target))

    meta["applied"] = True
    meta["applied_at"] = time.time()
    meta["applied_to"] = str(dst_root)
    meta_p.write_text(json.dumps(meta, indent=2), encoding="utf-8")

    return {
        "ok": True,
        "kb_id": kb_id,
        "applied_to": str(dst_root),
        "files": copied,
    }
